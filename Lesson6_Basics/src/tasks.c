// Задание 21. Сортировка пузырьком по возрастанию: 5 1 4 2 → 1 2 4 5.
void bubble_sort(int* arr, int n)
{
    for (int pass = 0; pass < n - 1; pass++) {
        for (int j = 0; j < n - 1 - pass; j++) {
            if (arr[j] < arr[j + 1]) {   // ??? сейчас сортирует по убыванию. Когда соседей надо менять?
                int tmp = arr[j];
                arr[j] = arr[j + 1];
                arr[j + 1] = tmp;
            }
        }
    }
}
