// tickets.c — файл заданий урока 5.
// Здесь 4 функции, в каждой спрятан баг. Писать заново ничего не нужно:
// найди и поправь одну-две строки. Делай по порядку: следующие функции пользуются предыдущими.
#include "life.h"

#include <stdlib.h>

// =====================================================================
// Задание 1. Где лежит клетка (сцена 1)
// Поле хранится одной строкой: сначала весь ряд y = 0, потом весь ряд y = 1, и так далее.
// Симптом: кликаешь в одну клетку — загорается другая.
// =====================================================================
int cell_index(const Grid* g, int x, int y)
{
    return x * g->w + y;
}

// =====================================================================
// Задание 2. Соседи (сцена 2)
// Поле замкнуто, как бублик: левый сосед клетки с x = 0 — это клетка с x = w - 1.
// Симптом: у клеток на левом и верхнем краю неправильное число соседей.
// =====================================================================
int count_neighbors(const Grid* g, int x, int y)
{
    int count = 0;
    for (int dy = -1; dy <= 1; dy++) {
        for (int dx = -1; dx <= 1; dx++) {
            if (dx == 0 && dy == 0) continue;     // саму клетку не считаем
            int nx = (x + dx) % g->w;             // заворачиваем через край
            int ny = (y + dy) % g->h;
            count += g->cur[cell_index(g, nx, ny)];
        }
    }
    return count;
}

// =====================================================================
// Задание 3. Одно поколение (сцена 3)
// Правила: живая клетка с 2 или 3 соседями живёт, мёртвая с ровно 3 соседями оживает, остальные умирают.
// Симптом: поле мигает, а планер разваливается.
// =====================================================================
void life_step(Grid* g)
{
    for (int y = 0; y < g->h; y++) {
        for (int x = 0; x < g->w; x++) {
            int n = count_neighbors(g, x, y);
            int i = cell_index(g, x, y);
            int alive = g->cur[i];
            g->cur[i] = (alive && (n == 2 || n == 3)) || (!alive && n == 3);
        }
    }

    // меняем местами указатели: следующее поколение становится текущим
    unsigned char* tmp = g->cur;
    g->cur = g->next;
    g->next = tmp;
}

// =====================================================================
// Задание 4. Новый размер поля (сцена 4)
// Симптом: каждый раз, когда меняешь размер, в «Куче» становится на 2 блока больше.
// =====================================================================
void grid_resize(Grid* g, int w, int h)
{
    unsigned char* cur = calloc(w * h, 1);
    unsigned char* next = calloc(w * h, 1);

    // переносим ту часть рисунка, которая влезает в новое поле
    for (int y = 0; y < h && y < g->h; y++)
        for (int x = 0; x < w && x < g->w; x++)
            cur[y * w + x] = g->cur[y * g->w + x];

    g->cur = cur;
    g->next = next;
    g->w = w;
    g->h = h;
}
